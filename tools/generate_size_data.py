MEASURE_DOC = """# 量体方法:如何准确测量身体尺寸

## 一、身高
光脚靠墙站立,脚跟、臀部、肩胛骨、后脑勺四点贴墙,用直角尺压在头顶量取读数。早晚身高差约 1cm,建议固定时间测量。

## 二、体重
早晨起床空腹、排空后测量最准确,连续 3 天取平均值。

## 三、胸围
软尺从腋下水平绕胸部最丰满处一圈,保持自然呼吸,软尺贴肤但不勒紧,读数加 2cm 余量。

## 四、腰围
软尺绕肚脐上方 2cm(腰部最细处)水平一圈,自然呼吸状态测量。买裤子按这个腰围选码。

## 五、臀围
软尺绕臀部最丰满处水平一圈。臀围比腰围大 28cm 以上属于梨形身材,选裤装时按臀围选码。

## 六、肩宽
从一侧肩骨最高点到另一侧肩骨最高点的距离,测量时双臂自然下垂。

## 七、脚长
光脚站立踩在白纸上,标记最长脚趾到脚跟的最远距离。

## 八、测量工具
使用 1.5 米软尺(服装软尺),不要用钢卷尺(会压平身体曲线,数据偏小)。
"""

