def make_md(p, out: Path):
    """生成商品详情 markdown"""
    lines = [f"# {p['name']}({p['category']})", "", f"**型号**: {p['model']}",
             f"**价格**: {p['price']}", "", "## 核心参数", ""]
    lines += [f"- {x}" for x in p["params"]]
    lines += ["", "## 产品亮点", ""]
    lines += [f"- {x}" for x in p["highlights"]]
    lines += ["", "## 常见问题", ""]
    for q, a in p["faqs"]:
        lines += [f"**Q: {q}**", f"A: {a}", ""]
    out.write_text("\n".join(lines), encoding="utf-8")


