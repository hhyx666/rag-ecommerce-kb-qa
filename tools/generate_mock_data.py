def make_pdf(title, sections, out: Path):
    """生成 PDF 手册(用微软雅黑字体)"""
    doc = fitz.open()
    page = doc.new_page()
    y = 70
    page.insert_text(fitz.Point(72, y), title, fontsize=16, fontname="cn", fontfile=FONT)
    y += 40
    for heading, paras in sections:
        page.insert_text(fitz.Point(72, y), heading, fontsize=12, fontname="cn", fontfile=FONT)
        y += 24
        for para in paras:
            # 简单换行:按行插入
            for line in [para[i : i + 38] for i in range(0, len(para), 38)]:
                page.insert_text(fitz.Point(72, y), line, fontsize=10, fontname="cn", fontfile=FONT)
                y += 16
                if y > 780:
                    page = doc.new_page()
                    y = 70
            y += 6
        y += 10
    doc.save(str(out))
    doc.close()


